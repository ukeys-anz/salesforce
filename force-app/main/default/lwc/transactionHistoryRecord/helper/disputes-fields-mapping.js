// Mapping for card dispute type, key is Salesforce field, value is the payload's key
const cardDisputesFieldsMapping = {
  Card_Number__c: "card.last_four_digits",
  Card_Scheme__c: "card.scheme",
  Date_Posted__c: "transaction_posted_date",
  Description: "long_desc",
  Effective_Date__c: "transaction_date",
  Posted_Amount__c: "amount.value",
  Posted_Currency__c: "amount.currency_code",
  Transaction_Amount__c: "international_amount.charged.value",
  Transaction_Currency__c: "international_amount.charged.currency_code",
  Transaction_Id__c: "origination_id",
  Transaction_Type__c: "type",
  Transaction_UUID__c: "transaction_id"
};

// Pre-populate fields that are passed individually from the lwc, which we cannot loop through
function prepopulateCommonFields(personAccountId, financialAccountId) {
  let defaultFieldValuesObj = {
    Subject: "To be generated by the system",
    AccountId: personAccountId ? personAccountId : "",
    FinServ__FinancialAccount__c: financialAccountId ? financialAccountId : ""
  };
  return defaultFieldValuesObj;
}

// Pre-populate all disputes field, including common and dispute-type-specific fields
export function prepopulateDisputesFields(
  personAccountId,
  financialAccountId,
  transactionType,
  transaction
) {
  let defaultFieldValuesObj = prepopulateCommonFields(
    personAccountId,
    financialAccountId
  );
  switch (transactionType) {
    case "Card":
      defaultFieldValuesObj = prepopulateFieldsValues(
        cardDisputesFieldsMapping,
        transaction,
        defaultFieldValuesObj
      );
      return defaultFieldValuesObj;
      break;
    //  Other dispute types to be added here
    default:
    // code block
  }
}

// Pre-populate default field values object using the mappings above
const prepopulateFieldsValues = (
  fieldMappings,
  transaction,
  defaultFieldValuesObj
) => {
  Object.entries(fieldMappings).forEach(([key, value], index) => {
    let keyString = value;
    defaultFieldValuesObj[key] = !keyString.includes(".") // If this key does not contain nested value
      ? transaction[keyString] // extract the value using the native way
      : getNestedValue(transaction, keyString); // otherwise call getNestedValue
  });
  return defaultFieldValuesObj;
};

// Return the nested value for a specific key in the payload
function getNestedValue(transaction, keyString) {
  let keyArray = keyString.split(".");
  var result = transaction;
  keyArray.forEach((key) => {
    if (result[key] !== undefined) {
      result = result[key];
    } else {
      result = "";
    }
  });
  return result;
}
