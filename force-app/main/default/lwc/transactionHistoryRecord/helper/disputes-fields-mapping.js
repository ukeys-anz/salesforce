// Mapping for card dispute type, key is Salesforce field, value is the payload's key
const cardDisputesFieldsMapping = {
  Card_Number__c: "card.last_four_digits",
  Card_Scheme__c: "card.scheme",
  Transaction_Amount__c: "international_amount.charged.value",
  Transaction_Currency__c: "international_amount.charged.currency_code",
  Card_Token_Number__c: "tokenizedCardNumber"
};

const atmDisputesFieldsMapping = {
  Transaction_Amount__c: "international_amount.charged.value",
  Transaction_Currency__c: "international_amount.charged.currency_code",
  Bank_ATM__c: "long_desc",
  Location__c: "long_desc",
  Card_Scheme__c: "cash.card_scheme",
  Card_Number__c: "cash.card_last_four_digits",
  Card_Token_Number__c: "tokenizedCardNumber"
};

const directDebitDisputesFieldsMapping = {
  AuxDomId__c: "aux_dom.value",
  Crediting_Trace_Line__c: "traceId"
};

const directEntryDisputesFieldsMapping = {
  Receipt__c: "pay_anyone.payment_receipt_number.value",
  Crediting_Trace_Line__c: "traceId",
  Crediting_Account_Name__c: "pay_anyone.other_entity.name",
  Crediting_Account_Number__c:
    "pay_anyone.other_entity.account.transactionAccountNumber",
  Crediting_Account_BSB__c: "pay_anyone.other_entity.account.bsb"
};

const nppDisputesFieldsMapping = {
  Payment_ID__c: "pay_anyone.payment_id",
  Receipt__c: "pay_anyone.payment_receipt_number.value"
};

const commonFieldsMapping = {
  Effective_Date__c: "transaction_date",
  Posted_Amount__c: "amount.value",
  Posted_Currency__c: "amount.currency_code",
  Transaction_Description__c: "short_desc",
  Date_Posted__c: "transaction_posted_date",
  Transaction_Id__c: "origination_id",
  Transaction_UUID__c: "transaction_id",
  Transaction_Type__c: "type"
}; // Common fields between all dispute types from the payload

// Pre-populate fields that are passed individually from the lwc, which we cannot loop through
function prepopulateCommonFields(
  personAccountId,
  financialAccountId,
  transaction
) {
  let defaultFieldValuesObj = {
    Subject: "To be generated by the system",
    AccountId: personAccountId ? personAccountId : "",
    FinServ__FinancialAccount__c: financialAccountId ? financialAccountId : "",
    Origin: ""
  };
  defaultFieldValuesObj = prepopulateFieldsValues(
    commonFieldsMapping,
    transaction,
    defaultFieldValuesObj
  );

  return defaultFieldValuesObj;
}

// Pre-populate all disputes field, including common and dispute-type-specific fields
export function prepopulateDisputesFields(
  personAccountId,
  financialAccountId,
  disputeType,
  transaction,
  tokenizedCardNumberString
) {
  let defaultFieldValuesObj = prepopulateCommonFields(
    personAccountId,
    financialAccountId,
    transaction
  );
  let mappingObj;
  switch (disputeType) {
    case "Card":
      mappingObj = cardDisputesFieldsMapping;
      break;
    case "ATM":
      mappingObj = atmDisputesFieldsMapping;
      break;
    case "Direct Debit":
      mappingObj = directDebitDisputesFieldsMapping;
      break;
    case "Direct Entry":
      mappingObj = directEntryDisputesFieldsMapping;
      break;
    case "NPP":
      mappingObj = nppDisputesFieldsMapping;
      break;
  }

  defaultFieldValuesObj = mappingObj
    ? prepopulateFieldsValues(
        mappingObj,
        transaction,
        defaultFieldValuesObj,
        tokenizedCardNumberString
      )
    : defaultFieldValuesObj;

  return defaultFieldValuesObj;
}

// Pre-populate default field values object using the mappings above
const prepopulateFieldsValues = (
  fieldMappings,
  transaction,
  defaultFieldValuesObj,
  tokenizedCardNumberString
) => {
  Object.entries(fieldMappings).forEach(([key, value], index) => {
    //Posted date is only available the day after the transaction is made,
    //so we need to have this check here to make sure we don't populate the date field
    //if its invalid
    if (
      value === "transaction_posted_date" &&
      (!transaction[value] || transaction[value] === "Invalid Date")
    ) {
      return;
    }

    let keyString = value;
    defaultFieldValuesObj[key] = !keyString.includes(".") // If this key does not contain nested value
      ? transaction[keyString] // extract the value using the native way
      : getNestedValue(transaction, keyString); // otherwise call getNestedValue

    // Set Tokenized Card field with String received from API call
    if (value === "tokenizedCardNumber" && tokenizedCardNumberString) {
      defaultFieldValuesObj[key] = tokenizedCardNumberString;
    }

    //Check if the value is unknown so we don't prepopulate the field
    //to avoid validation rules preventing case creation
    //ie BSB being prepopulated with unknown triggers VR
    if (defaultFieldValuesObj[key] === "Unknown") {
      defaultFieldValuesObj[key] = null;
    }
  });

  return defaultFieldValuesObj;
};

// Return the nested value for a specific key in the payload
function getNestedValue(transaction, keyString) {
  let keyArray = keyString.split(".");
  var result = transaction;
  keyArray.forEach((key) => {
    if (result[key] !== undefined) {
      result = result[key];
    } else {
      result = "";
    }
  });
  return result;
}
